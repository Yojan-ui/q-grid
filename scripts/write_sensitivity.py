"""Sensitivity of the RVCE results to contract demand, battery wear and value of lost load (low / base / high).

  python scripts/write_sensitivity.py    -> results/sensitivity/summary.json, summary.csv, docs/sensitivity.md

Each case is a run of scripts/run_bench_v3.py on the 30 RVCE days with one config value changed through
QGRID_CONFIG_OVERRIDE (recorded in the case's run_info.json); methods: status quo, rule-based, per-building MPC, Q-Grid
and the best possible plan. "base" is the main RVCE run (results/bench_v3). Scoring is write_bench_v3.daily with the
case's own config (so a different contract demand changes the monthly bill too). Gap reference = the cheapest feasible
plan of the day among the methods run (no certified bounds in the sensitivity runs).
"""
from __future__ import annotations

import json
import os
import sys
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
sys.path[:0] = [str(ROOT / "backend"), str(ROOT / "scripts")]
SDIR = ROOT / "results" / "sensitivity"
CASES = [("contract_1000", "Contract demand", "low", "1,000 kVA"), ("base", "Contract demand", "base", "1,300 kVA"),
         ("contract_1600", "Contract demand", "high", "1,600 kVA"),
         ("wear_low", "Battery wear", "low", "Rs 15,000/kWh battery"), ("base", "Battery wear", "base", "Rs 25,000/kWh battery"),
         ("wear_high", "Battery wear", "high", "Rs 35,000/kWh battery"),
         ("voll_low", "Value of lost load", "low", "Rs 20 / 500 per kWh"), ("base", "Value of lost load", "base", "Rs 40 / 1,000 per kWh"),
         ("voll_high", "Value of lost load", "high", "Rs 80 / 2,000 per kWh")]
METHODS = {"status_quo": "Status quo", "rule_based": "Rule-based", "per_building_mpc": "Per-building MPC", "qgrid": "Q-Grid",
           "optimum": "Best possible plan"}


def score(d: Path) -> pd.DataFrame:
    import write_bench_v3 as wb
    from qgrid import data as qd
    info = json.loads((d / "run_info.json").read_text(encoding="utf-8"))
    ov = info.get("config_override")
    old = os.environ.pop("QGRID_CONFIG_OVERRIDE", None)
    if ov:
        os.environ["QGRID_CONFIG_OVERRIDE"] = ov
    cfg = qd.load_config()
    os.environ.pop("QGRID_CONFIG_OVERRIDE", None)
    if old:
        os.environ["QGRID_CONFIG_OVERRIDE"] = old
    r = pd.read_csv(d / "runs.csv")
    r = r[(r.dataset == "rvce") & r.method.isin(METHODS)]
    tmp = SDIR / "_scoring"; tmp.mkdir(parents=True, exist_ok=True)
    r.to_csv(tmp / "runs.csv", index=False)
    obj = r.objective_plan_rs if "objective_plan_rs" in r else r.objective_rs
    b = r.assign(o=obj)[r.method == "optimum"].groupby(["dataset", "day"]).o.min().reset_index()
    b = b.rename(columns={"o": "opt_central"}); b["LB"] = b.opt_central
    b.to_csv(tmp / "bounds.csv", index=False)
    wb.OUT = tmp
    out = wb.daily(cfg)
    return out


def main():
    rows, summ = [], {}
    cache = {}
    for case, factor, level, label in CASES:
        d = ROOT / "results" / "bench_v3" if case == "base" else SDIR / case
        if not (d / "runs.csv").exists():
            print(f"skip {case}: {d}/runs.csv missing"); continue
        if case not in cache:
            cache[case] = score(d)
        r = cache[case]
        for m, name in METHODS.items():
            g = r[r.method == m]
            if not len(g):
                continue
            rows.append({"factor": factor, "level": level, "setting": label, "case": case, "method": m, "name": name, "n_days": len(g),
                         "gap_pct": g.gap_pct.mean(), "saving_pct": g.saving_pct.mean(), "bill_rs_day": g.bill_rs.mean(),
                         "critical_downtime_h": g.critical_downtime_h.mean(), "wear_rs_day": g.wear_rs.mean(),
                         "battery_cycles": g.battery_cycles.mean(), "dg_litres_day": g.dg_litres.mean()})
        q = r[r.method == "qgrid"]
        summ[case] = {"qgrid_gap_pct": float(q.gap_pct.mean()), "qgrid_saving_pct": float(q.saving_pct.mean()),
                      "qgrid_downtime_h": float(q.critical_downtime_h.mean()), "qgrid_cycles": float(q.battery_cycles.mean()),
                      "n_days": float(len(q))}
    s = pd.DataFrame(rows)
    SDIR.mkdir(parents=True, exist_ok=True)
    s.to_csv(SDIR / "summary.csv", index=False)
    (SDIR / "summary.json").write_text(json.dumps(summ, indent=1), encoding="utf-8")
    L = ["# Sensitivity: contract demand, battery wear, value of lost load\n",
         "_Generated by `scripts/write_sensitivity.py` from `results/sensitivity/*/runs.csv` and `results/bench_v3/runs.csv` "
         "(base). Each case: the 30 RVCE days, one config value changed (`QGRID_CONFIG_OVERRIDE`, recorded in the case's "
         "`run_info.json`), every method re-run and re-scored with that value. Gap reference = cheapest feasible plan "
         "among the methods run. All three factors are ASSUMPTIONS; the contract demand awaits an RVCE bill._\n"]
    for factor in dict.fromkeys(c[1] for c in CASES):
        g = s[s.factor == factor] if len(s) else s
        if not len(g):
            continue
        L += [f"## {factor}\n", "| Setting | Method | Gap % | Bill saving vs status quo % | Critical downtime h/day | Battery cycles/day | Wear Rs/day |",
              "|---|---|---:|---:|---:|---:|---:|"]
        for _, x in g.iterrows():
            L.append(f"| {x.level}: {x.setting} | {x['name']} | {x.gap_pct:.2f} | {x.saving_pct:.1f} | {x.critical_downtime_h:.2f} | "
                     f"{x.battery_cycles:.2f} | {x.wear_rs_day:,.0f} |")
        L.append("")
    (ROOT / "docs" / "sensitivity.md").write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"wrote results/sensitivity/summary.* and docs/sensitivity.md ({len(summ)} cases)")


if __name__ == "__main__":
    main()
