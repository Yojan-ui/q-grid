"""docs/consistency.md: explains apparent inconsistencies in earlier results, with every number read from results/.

  python scripts/write_consistency.py
"""
from __future__ import annotations

import sys
from pathlib import Path

import numpy as np
import pandas as pd
import yaml

ROOT = Path(__file__).resolve().parents[1]


def main():
    cfg = yaml.safe_load((ROOT / "config.yaml").read_text())
    oc = cfg["outage_costs"]
    b = pd.read_csv(ROOT / "results" / "v2" / "benchmark_v2.csv")
    s = b[b.scenario != "eval"]
    piv = s.pivot_table(index="scenario", columns="method", values="gap_to_opt_pct")
    o = b[(b.scenario == "outage_fest")].set_index("method")
    qa, ex, opt = o.loc["V2-QAOA"], o.loc["V2-EXACT"], o.loc["B4-DC"]
    wins = int((piv["V2-QAOA"] < piv["V2-EXACT"] - 1e-9).sum()); losses = int((piv["V2-QAOA"] > piv["V2-EXACT"] + 1e-9).sum())
    ties = len(piv) - wins - losses
    # money-only gap (no value of lost load): objective minus VoLL, vs the optimum's
    b["obj_novoll"] = b.objective_incl_demand_rs - (b.objective_rs - b.cost_rs)
    optn = b[b.method == "B4-DC"].set_index(["scenario", "day"])["obj_novoll"]
    b["gap_novoll_pct"] = [100 * (r.obj_novoll - optn.get((r.scenario, r.day), np.nan)) / optn.get((r.scenario, r.day), np.nan)
                           for r in b.itertuples()]
    rows = []
    names = {"V1": "Earlier prototype (1-hour horizon, binary coordination)", "V2-EXACT": "Hybrid Benders, exact master",
             "V2-QAOA": "Hybrid Benders, QAOA master", "V2-QIEA": "Hybrid Benders, QIEA master (quantum-inspired, classical)"}
    for m in ["V1", "V2-EXACT", "V2-QAOA", "V2-QIEA"]:
        sub = b[(b.method == m) & (b.scenario != "eval")]
        rows.append(f"| {names[m]} | {sub.gap_to_opt_pct.mean():.2f} | {sub.gap_novoll_pct.mean():.2f} |")
    lines = [
        "# Consistency notes\n",
        "_Generated by `scripts/write_consistency.py` from `results/v2/benchmark_v2.csv` (the earlier hybrid-Benders benchmark, "
        "computed on the previous template load profiles) and `config.yaml`._\n",
        "## 1. Why the QAOA-master variant beat the exact-master variant on the outage day\n",
        f"On the outage day the Benders variant with a QAOA master landed {qa.gap_to_opt_pct:.2f} % from the optimum and the variant "
        f"with an exact master {ex.gap_to_opt_pct:.2f} % (a difference of Rs {ex.objective_incl_demand_rs - qa.objective_incl_demand_rs:,.0f} "
        f"on Rs {opt.objective_incl_demand_rs:,.0f}). Over the six named days the QAOA master was better on {wins}, worse on {losses} "
        f"and tied on {ties}.\n",
        "Cause — 'exact master' did not mean an exact decision:",
        "- Each hour the master MILP was solved to optimality (HiGHS, relative gap 1e-6), but the Benders loop stopped at an "
        f"iteration cap (6) with a bound gap still open: {ex.benders_gap_mean_pct:.2f} % (exact master) and "
        f"{qa.benders_gap_mean_pct:.2f} % (QAOA master) on average on that day. The decision taken was the best plan found so far, "
        "not a proven optimum.",
        "- Both variants also share consensus ADMM stopped at a 1 kW tolerance and a trust region on the master.",
        "- The two variants therefore follow different, path-dependent trajectories through the day; a difference of "
        f"{100 * (ex.objective_incl_demand_rs - qa.objective_incl_demand_rs) / opt.objective_incl_demand_rs:.2f} % is well inside the "
        "open Benders gap. It is noise of the heuristic, not evidence that QAOA finds better plans.",
        "- Resolution in the current design: the Benders loop is gone. Each building's commitment is solved exactly by branch and "
        "bound at the agreed prices, so 'exact' means exact for that sub-problem, and the remaining gap is measured and certified "
        "against proven lower bounds (docs/math.md).\n",
        "## 2. A 0.2 % gap next to 1.75 h of critical downtime\n",
        f"Both numbers come from the same run (QAOA-master variant, outage day): gap {qa.gap_to_opt_pct:.2f} %, critical downtime "
        f"{qa.critical_downtime_h:.2f} h, critical energy unserved {qa.critical_unserved_kwh:.3f} kWh "
        f"(optimum: {opt.critical_downtime_h:.2f} h, {opt.critical_unserved_kwh:.3f} kWh).",
        "- Critical downtime counts every 15-min slot in which *any* critical load is unserved, however small (> 1e-6 kW). Here the "
        f"shortfall over the whole day was {qa.critical_unserved_kwh:.3f} kWh, spread over {int(round(qa.critical_downtime_h * 4))} "
        "slots — numerical crumbs of a solver tolerance, not a real blackout of a critical load.",
        f"- At the value of lost load used for critical load (Rs {oc['voll_critical_rs_kwh']}/kWh) that shortfall is worth about "
        f"Rs {qa.critical_unserved_kwh * oc['voll_critical_rs_kwh']:,.0f}, which is why the gap barely moves.",
        "- In the multi-dataset benchmark both measures are reported side by side: strict downtime (any shortfall) and downtime counting only "
        "slots where more than 1 % of the critical load is unserved, plus the unserved energy itself.\n",
        "## 3. Value of lost load (VoLL) and gaps with and without it\n",
        f"- VoLL used inside the objective: non-critical load Rs {oc['voll_noncritical_rs_kwh']}/kWh, critical load "
        f"Rs {oc['voll_critical_rs_kwh']}/kWh.",
        "- Source: **ASSUMPTION** (config.yaml `outage_costs`). No official Indian or BESCOM VoLL figure has been sourced; it is "
        "a modelling choice that makes shedding load never 'cheaper' than serving it.",
        "- Every gap is reported both ways. With VoLL = objective including the value of lost load (what the optimisers minimise). "
        "Without VoLL = money only (energy + diesel + demand charge + terminal value); a method can look better on money alone by "
        "shedding more load, which is why the VoLL version is the primary one.\n",
        "| Design (earlier benchmark, six named days) | gap with VoLL % | gap without VoLL (money only) % |",
        "|---|---:|---:|",
        *rows,
    ]
    (ROOT / "docs" / "consistency.md").write_text("\n".join(lines) + "\n")
    print("wrote docs/consistency.md")


if __name__ == "__main__":
    sys.exit(main())
